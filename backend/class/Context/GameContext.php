<?php declare(strict_types=1);

namespace noxkiwi\spotigame\Context;

use Exception;
use noxkiwi\core\ErrorHandler;
use noxkiwi\core\Helper\LinkHelper;
use noxkiwi\core\Helper\WebHelper;
use noxkiwi\spotigame\Exception\GameOverException;
use noxkiwi\spotigame\GameEntity\GameMode\GameMode;
use noxkiwi\spotigame\GameEntity\Sitting\Sitting;
use noxkiwi\spotigame\Helper\SpotifyRedirect;
use noxkiwi\spotigame\Model\SittingModel;
use noxkiwi\spotigame\Verification\Verification;
use function header;

